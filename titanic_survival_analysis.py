"""Titanic_Survival_Analysis.ipynb"""

import matplotlib.pyplot as plt
import pandas as pd
import seaborn as sns

data = {
    "PassengerId": [1, 2, 3, 4, 5, 6, 7, 8],
    "Survived": [0, 1, 1, 1, 0, 0, 1, 0],
    "Pclass": [3, 1, 3, 1, 3, 3, 2, 1],
    "Sex": ["male", "female", "female", "female", "male", "male", "female", "male"],
    "Age": [22.0, 38.0, 26.0, 35.0, 35.0, 28.0, 27.0, 54.0],
}

df = pd.DataFrame(data)

print("--- Dataset Preview ---")
print(df)

print("\n--- Survival Rate by Gender ---")
print(df.groupby("Sex")["Survived"].mean())

print("\n--- Survival Rate by Class ---")
print(df.groupby("Pclass")["Survived"].mean())

sns.set_theme(style="whitegrid")

fig, axes = plt.subplots(1, 3, figsize=(15, 4))

sns.barplot(x="Sex", y="Survived", data=df, ax=axes[0], hue="Sex", legend=False, palette="Set2")
axes[0].set_title("Survival Rate by Gender")

sns.barplot(x="Pclass", y="Survived", data=df,ax=axes[1], hue="Pclass", legend=False, palette="Set1")
axes[1].set_title("Survival Rate by Passenger Class")

sns.histplot(data=df, x="Age", hue="Survived",multiple="stack", ax=axes[2], palette="Blues")
axes[2].set_title("Age Distribution by Survival")

plt.tight_layout()
plt.show()